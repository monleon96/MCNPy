@dataclass
class Styles:
    """§9.1. The evaluation's styles, and the graph ``derivedFrom`` defines.

    Look-up is by label, because that is what a form carries. The chain
    resolution is the point of the node: given a processed form, walk back to
    the ``evaluated`` style it ultimately came from, and refuse to walk a cycle.
    """

    styles: List[Style] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.styles)

    def __iter__(self) -> Iterator[Style]:
        return iter(self.styles)

    def __bool__(self) -> bool:
        # A declared slot is *present* even when empty; only `len()` speaks to
        # content. Without this, `if suite.styles:` reads an evaluation that
        # models styles and has none yet as one that does not model them.
        return True

    def __getitem__(self, label: str) -> Style:
        for style in self.styles:
            if style.label == label:
                return style
        raise KeyError(
            f"no style labelled {label!r}; have {[s.label for s in self.styles]}"
        )

    def add(self, style: Style) -> None:
        if any(s.label == style.label for s in self.styles):
            raise StyleError(f"duplicate style label {style.label!r}")
        self.styles.append(style)

    def chain(self, label: str) -> List[Style]:
        """``[style, its parent, ..., the root]``.

        Raises on a dangling ``derivedFrom`` and on a cycle. A cycle is not a
        hypothetical: ``derivedFrom`` is a free-text label, so two styles naming
        each other is a single typo away, and the failure without this check is
        a hang rather than an error.
        """
        seen: List[str] = []
        out: List[Style] = []
        current: Optional[str] = label
        while current is not None:
            if current in seen:
                raise StyleError(
                    f"derivedFrom cycle: {' -> '.join(seen + [current])}"
                )
            seen.append(current)
            try:
                style = self[current]
            except KeyError as exc:
                raise StyleError(
                    f"style {seen[-2] if len(seen) > 1 else label!r} is derivedFrom "
                    f"{current!r}, which does not exist"
                ) from exc
            out.append(style)
            current = style.derivedFrom
        return out

    def rootOf(self, label: str) -> Style:
        """The style at the end of the ``derivedFrom`` chain."""
        return self.chain(label)[-1]

    def evaluatedFor(self, label: str) -> Evaluated:
        """The ``evaluated`` style a processed form ultimately derives from.

        This is the question ``MF34_to_MG`` could not answer and therefore had
        to refuse: *whose* σ am I weighting with. Here it is a graph walk.
        """
        for style in self.chain(label):
            if isinstance(style, Evaluated):
                return style
        raise StyleError(
            f"no evaluated style in the derivedFrom chain of {label!r}: "
            f"{[s.label for s in self.chain(label)]}"
        )

    @property
    def labels(self) -> List[str]:
        return [s.label for s in self.styles]
