class StyleError(ValueError):
    """A ``styles`` node is inconsistent — a dangling or circular ``derivedFrom``."""


@dataclass
class Style:
    """Base for the §9 styles. ``label`` identifies it; forms refer to it by label."""

    label: str
    derivedFrom: Optional[str] = None
    date: Optional[str] = None

    #: The GNDS node name, which is *not* the class name lower-cased in every
    #: case (``MonteCarlo_cdf``, ``URR_probabilityTables``), so it is declared.
    gndsNodeName: str = field(default="style", init=False, repr=False)

    #: Whether §9 requires this style to name what it was derived from.
    derivedFromRequired: bool = field(default=False, init=False, repr=False)

    def __post_init__(self) -> None:
        if self.derivedFromRequired and not self.derivedFrom:
            raise StyleError(
                f"the {self.gndsNodeName!r} style requires derivedFrom (§9.3.1); "
                f"style {self.label!r} has none"
            )


def _style(nodeName: str, *, requiresDerivedFrom: bool = False):
    """Declare a concrete style class carrying its GNDS node name."""

    def decorate(cls):
        cls.gndsNodeName = nodeName
        cls.derivedFromRequired = requiresDerivedFrom
        return cls

    return decorate


@_style("evaluated")
@dataclass
class Evaluated(Style):
    """§9.2.1. Data as created by the evaluator. More than one is allowed.

    ``temperature`` and ``projectileEnergyDomain`` are children the schema makes
    **mandatory** on this style (``RS_EvaluatedType``), and all 558 neutron
    evaluations carry both. They are fields rather than reported losses because
    they are data: dropping the temperature leaves nothing distinguishing a 0 K
    evaluation from a broadened one, and dropping the domain leaves nothing
    saying what the evaluation was written *for* — which is not the same
    statement as the union of its reactions' domains.
    """

    library: Optional[str] = None
    version: Optional[str] = None
    temperature: Optional[PhysicalQuantity] = None
    projectileEnergyDomain: Optional[RangeQuantity] = None


