"""GNDS-2.1 §9-10: ``styles``, and the chain each style was derived through.

**What a style is for.** §9.1: a data container holds several *forms*, each
tagged with the ``label`` of a style, and the ``styles`` node records how each
style was derived from another via ``derivedFrom``. The spec's own example is
exactly kika's situation — a ``crossSection`` holding a
``resonancesWithBackground`` form labelled ``eval`` and an ``XYs1d`` form
labelled ``recon``.

That is the structure kika has been missing. Today `endf.pendf` is a dict
hanging off the side of an ``ENDF`` object, populated by whichever reconstructor
the caller chose, with nothing recording *which* — which is the whole reason
``MF34_to_MG`` had to be made to raise rather than guess a σ. Here the
provenance is the model: a ``crossSectionReconstructed`` style whose
``derivedFrom`` names the ``evaluated`` style it came from.

**The ``realization`` style (§9.3) is the standards-blessed home for the Fe-56
perturbed ensemble.** §9.3 defines it for *"data that was randomly generated by
sampling from probability distributions and/or covariance matrices"*, and
§9.3.1 makes ``derivedFrom`` **required** on it: *"The derivedFrom node must
point to the evaluated style containing the covariances and/or probabilities
that were sampled to produce this realization."* Phase 8 emits the thesis
ensemble this way.
"""
